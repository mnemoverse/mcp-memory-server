#!/usr/bin/env node
/**
 * generate-tools-manifest.mjs
 *
 * The tool list as a generated, published artifact: tools.json at the repo
 * root, derived from the BUILT server rather than from a hand-kept list.
 *
 * Reads:  dist/shared.js (registerMemoryTools, the package's own build)
 *         package.json (name, version)
 * Writes: tools.json
 *
 * Usage:
 *   node scripts/generate-tools-manifest.mjs            # generate
 *   node scripts/generate-tools-manifest.mjs --check    # regenerate in memory, diff against the committed file
 *
 * Exit codes:
 *   0  written, or --check found no difference
 *   1  --check found a difference (or tools.json is missing / unparseable)
 *   2  dist/shared.js is missing: run `npm run build` first
 *
 * WHY. Before this file, the .mcpb manifest's tools[] was a hand list in
 * src/configs/source.json (ten entries) while src/tools.ts registered eleven,
 * and about thirty prose copies of "ten tools" sat across the repo and its
 * downstream docs. A list typed by hand drifts the first time the code
 * changes; a list produced by asking the built server what it registers
 * cannot. scripts/generate-configs.mjs now reads this file for the .mcpb
 * manifest, and test/tools-manifest.test.ts pins it to a live in-memory
 * server and to the prose that states the count.
 *
 * HOW. The same seam test/direct-register.ts uses: registerMemoryTools on a
 * fresh McpServer, a Client over InMemoryTransport, tools/list. `apiFetch` is
 * a stub that throws, because listing must never reach the API; if it ever
 * does, the throw is the signal.
 *
 * `title`: the SDK's tools/list emits a top-level `title` only when the tool
 * was registered with one (`registerTool(name, { title, ... })`). These tools
 * declare their title under `annotations.title` instead (src/tools.ts), so
 * the listing's top-level `title` is undefined and the value is taken from
 * `annotations.title`. The field is kept in the artifact as `title` so a
 * consumer does not need to know which of the two places the SDK put it.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT = resolve(__dirname, "..");

const SHARED_PATH = resolve(ROOT, "dist/shared.js");
const OUTPUT_PATH = resolve(ROOT, "tools.json");
const SCRIPT_REL = "scripts/generate-tools-manifest.mjs";

const checkMode = process.argv.includes("--check");

if (!existsSync(SHARED_PATH)) {
  console.error(`✗ ${SHARED_PATH} not found: run npm run build first`);
  process.exit(2);
}

const pkg = JSON.parse(readFileSync(resolve(ROOT, "package.json"), "utf8"));

// ─── Ask the built server what it registers ──────────────────────────────────

async function listRegisteredTools() {
  const { registerMemoryTools } = await import(pathToFileURL(SHARED_PATH).href);

  const server = new McpServer({ name: "tools-manifest", version: "0.0.0" });
  registerMemoryTools(server, {
    apiFetch: async (path) => {
      throw new Error(
        `${SCRIPT_REL}: apiFetch was called (${path}) while listing tools; listing must never reach the API`,
      );
    },
  });

  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  const client = new Client({ name: "tools-manifest-client", version: "0.0.0" });
  await server.connect(serverTransport);
  await client.connect(clientTransport);
  try {
    const { tools } = await client.listTools();
    return tools;
  } finally {
    await client.close();
    await server.close();
  }
}

function toEntry(tool) {
  const annotations = tool.annotations ?? {};
  return {
    name: tool.name,
    // See the header: top-level `title` when the SDK surfaces one, otherwise
    // the `annotations.title` these tools actually declare.
    title: tool.title ?? annotations.title,
    description: tool.description,
    annotations,
  };
}

function buildManifest(tools) {
  const entries = tools.map(toEntry).sort((a, b) => a.name.localeCompare(b.name, "en"));
  return {
    $comment: `generated by ${SCRIPT_REL} from the built server; do not edit`,
    name: pkg.name,
    version: pkg.version,
    count: entries.length,
    tools: entries,
  };
}

function serialize(manifest) {
  return JSON.stringify(manifest, null, 2) + "\n";
}

// ─── Check mode: say WHICH tools differ, not just that something does ────────

function explainDifference(committedText, fresh) {
  let committed;
  try {
    committed = JSON.parse(committedText);
  } catch (err) {
    console.error(`  committed tools.json does not parse: ${err.message || err}`);
    return;
  }
  for (const key of ["name", "version", "count"]) {
    if (committed[key] !== fresh[key]) {
      console.error(`  ${key}: committed ${JSON.stringify(committed[key])}, regenerated ${JSON.stringify(fresh[key])}`);
    }
  }
  const byName = (list) => new Map((Array.isArray(list) ? list : []).map((t) => [t.name, t]));
  const was = byName(committed.tools);
  const now = byName(fresh.tools);
  for (const name of was.keys()) {
    if (!now.has(name)) console.error(`  - ${name}: in the committed file, not registered by the built server`);
  }
  for (const name of now.keys()) {
    if (!was.has(name)) console.error(`  + ${name}: registered by the built server, missing from the committed file`);
  }
  for (const [name, entry] of now) {
    const old = was.get(name);
    if (!old) continue;
    const changed = ["title", "description", "annotations"].filter(
      (field) => JSON.stringify(old[field]) !== JSON.stringify(entry[field]),
    );
    if (changed.length) console.error(`  ~ ${name}: ${changed.join(", ")} differ`);
  }
}

// ─── Main ────────────────────────────────────────────────────────────────────

const manifest = buildManifest(await listRegisteredTools());
const content = serialize(manifest);

if (checkMode) {
  if (!existsSync(OUTPUT_PATH)) {
    console.error(`✗ tools.json is missing. Run \`node ${SCRIPT_REL}\` (or npm run build) and commit it.`);
    process.exit(1);
  }
  const committed = readFileSync(OUTPUT_PATH, "utf8").replace(/\r\n/g, "\n");
  if (committed !== content) {
    console.error("✗ Drift detected: tools.json does not match the built server");
    explainDifference(committed, manifest);
    console.error(`  Run \`node ${SCRIPT_REL}\` (or npm run build) and commit the result.`);
    process.exit(1);
  }
  console.log(`✓ tools.json in sync with the built server (${manifest.count} tools)`);
} else {
  const existing = existsSync(OUTPUT_PATH)
    ? readFileSync(OUTPUT_PATH, "utf8").replace(/\r\n/g, "\n")
    : "";
  if (existing === content) {
    console.log(`✓ tools.json unchanged (${manifest.count} tools)`);
  } else {
    writeFileSync(OUTPUT_PATH, content, "utf8");
    console.log(`✓ Generated tools.json (${manifest.count} tools)`);
  }
}
